// ПОМОЩНА — WHY TEXT за продуктовата карта
// =============================================================
function getWhyText(winner, answers) {
  var whyMap  = WHY_TEXT[winner];
  if (!whyMap) return '';
  var symptoms = answers['symptoms'] || [];
  // Намираме първия симптом, за който има специфичен текст
  for (var i = 0; i < symptoms.length; i++) {
    if (whyMap[symptoms[i]]) return whyMap[symptoms[i]];
  }
  // Fallback по focus_type
  var ft = answers['focus_type'];
  if (ft === 2 && whyMap['memory_decline']) return whyMap['memory_decline'];
  return whyMap['default'] || '';
}
