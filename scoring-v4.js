// ИЗЧИСЛЕНИЕ НА ФИНАЛНИЯ СКОР
// =============================================================
function computeFinalScores(answers) {
  var scores = { extra: 0, emotion: 0, move: 0, cerebro: 0, g24: 0 };

  // ── Q3 multi-select симптоми ──────────────────────────────
  var symptoms = answers['symptoms'] || [];
  symptoms.forEach(function(key) {
    var pts = SYMPTOM_SCORES[key];
    if (!pts) return;
    Object.keys(pts).forEach(function(prod) {
      scores[prod] = (scores[prod] || 0) + pts[prod];
    });
  });

  // ── Профилактика (без оплаквания) → Extra Health е основата ──
  // Без този ред профилактичен профил би спечелил Cerebro/G-24 само заради
  // възрастовата точка (всичко друго е 0). Extra Health е правилната основа.
  var isProphylactic = symptoms.length === 0 || (symptoms.length === 1 && symptoms[0] === 'none');
  if (isProphylactic) {
    scores.extra += 6;
  }

  // ── Q2 възраст ────────────────────────────────────────────
  var ageExact = parseInt(answers['age_exact'], 10);
  var ageRange = answers['age'];
  if (!isNaN(ageExact)) {
    if      (ageExact >= 55) { scores.g24 += 3; }
    else if (ageExact >= 45) { scores.g24 += 1; scores.cerebro += 1; }
    else                     { scores.cerebro += 1; }
  } else {
    if      (ageRange === 'over55') { scores.g24 += 3; }
    else if (ageRange === '45-55')  { scores.g24 += 1; scores.cerebro += 1; }
    else if (ageRange === '35-45' || ageRange === '25-35' || ageRange === '18-25') { scores.cerebro += 1; }
  }

  // ── Q4 продължителност ────────────────────────────────────
  var dur = answers['duration'];
  if (dur === 3) { scores.move += 1; scores.g24 += 1; }

  // ── Q5 сън ────────────────────────────────────────────────
  var sleep = answers['sleep'];
  if      (sleep === 1) scores.emotion += 2;
  else if (sleep === 2) scores.emotion += 3;
  else if (sleep === 3) scores.emotion += 4;

  // ── Q6 стрес ──────────────────────────────────────────────
  var stress = answers['stress'];
  if      (stress === 2) scores.emotion += 3;
  else if (stress === 3) scores.emotion += 4;

  // ── Q7 движение ───────────────────────────────────────────
  var movement = answers['movement'];
  if      (movement === 1) scores.move += 2;
  else if (movement === 2) scores.move += 3;
  else if (movement === 3) scores.move += 4;

  // ── Q8 имунитет ───────────────────────────────────────────
  var immunity = answers['immunity'];
  if      (immunity === 1) scores.extra += 2;
  else if (immunity === 2) scores.extra += 3;
  else if (immunity === 3) scores.extra += 4;

  // ── Q9 кожа ───────────────────────────────────────────────
  var skin = answers['skin'];
  if      (skin === 1) scores.extra += 2;
  else if (skin === 2) scores.extra += 3;
  else if (skin === 3) scores.extra += 4;

  // ── Q10 храносмилане ──────────────────────────────────────
  var digestion = answers['digestion'];
  if      (digestion === 1) scores.extra += 1;
  else if (digestion === 2) scores.extra += 2;
  else if (digestion === 3) scores.extra += 3;

  // ── Q11 енергия ───────────────────────────────────────────
  var energy = answers['energy'];
  if      (energy === 1) scores.emotion += 1;
  else if (energy === 2) { scores.g24 += 2; scores.extra  += 1; }
  else if (energy === 3) { scores.emotion += 1; scores.g24 += 2; }
  else if (energy === 4) { scores.extra += 2; scores.g24  += 1; }

  // ── Q12 памет & фокус ─────────────────────────────────────
  var focusType = answers['focus_type'];
  if      (focusType === 1) scores.cerebro += 4;
  else if (focusType === 2) scores.g24     += 5;
  else if (focusType === 3) { scores.g24 += 2; scores.cerebro += 1; }

  // ── Q13 начин на живот ────────────────────────────────────
  var lifestyle = answers['lifestyle'];
  if (lifestyle === 3) scores.extra += 1;

  // ── Q16 онкология — изключва Cerebro и G-24 ──────────────
  var noCerebroG24 = answers['oncology'] === 1;
  if (noCerebroG24) {
    scores.cerebro = 0;
    scores.g24     = 0;
  }

  // ── Нормализация по продукт ───────────────────────────────
  var pcts = {};
  Object.keys(scores).forEach(function(prod) {
    var max = MAX_SCORES[prod] || 1;
    pcts[prod] = Math.round((scores[prod] / max) * 100);
    if (pcts[prod] > 100) pcts[prod] = 100;
    if (pcts[prod] < 0)   pcts[prod] = 0;
  });

  // ── Сортиране и winner ────────────────────────────────────
  var sorted = Object.keys(pcts).sort(function(a, b) { return pcts[b] - pcts[a]; });
  var winner = sorted[0];

  // ── Combo (≤ 15% разлика) ─────────────────────────────────
  var runnerUp = null;
  var isCombo  = false;
  if (sorted.length > 1 && pcts[sorted[1]] > 0) {
    if ((pcts[winner] - pcts[sorted[1]]) <= 15) {
      runnerUp = sorted[1];
      isCombo  = true;
    }
  }

  // При профилактика показваме само Extra Health (основата) — без combo,
  // защото няма реални симптоми, които да оправдаят втори продукт.
  if (isProphylactic) {
    runnerUp = null;
    isCombo  = false;
  }

  // ── G-24 задължително показва Extra + Emotion като основа ─
  var g24Foundation = (winner === 'g24');

  return {
    scores:        scores,
    pcts:          pcts,
    sorted:        sorted,
    winner:        winner,
    runnerUp:      runnerUp,
    isCombo:       isCombo,
    g24Foundation: g24Foundation,
    noCerebroG24:  noCerebroG24
  };
}

